/**
 * Slice tests do not scan the @Configuration classes, so the real security has to be
 * imported. Without the @Import, Spring Boot's default configuration would be tested.
 * The mapper generated by MapStruct is a plain @Component, outside the web slice too.
 */
@WebMvcTest(controllers = OrderController.class,
        properties = "orderflow.auth.jwt-secret=" + OrderControllerTest.SECRET)
@Import({SecurityConfig.class, OrderWebMapperImpl.class})
class OrderControllerTest {

    static final String SECRET = "test-secret-for-the-web-slice-0123456789";

    @Autowired
    MockMvc mvc;
    @Autowired
    JwtEncoder jwtEncoder;

    @MockitoBean
    PlaceOrderUseCase placeOrder;
    @MockitoBean
    GetOrdersQuery getOrders;
    @MockitoBean
    CancelOrderUseCase cancelOrder;

    private static Order sampleOrder() {
        return Order.place("viktor", List.of(new OrderLine("KB-01", 2, new BigDecimal("49.90"))));
    }

    private static PageResult<Order> emptyPage() {
        return new PageResult<>(List.of(), 0, 10, false);
    }

    private static String token(JwtEncoder encoder, Instant expiresAt) {
        JwtClaimsSet claims = JwtClaimsSet.builder()
                .subject("viktor")
                .issuedAt(expiresAt.minus(Duration.ofHours(1)))
                .expiresAt(expiresAt)
                .build();
        return encoder.encode(JwtEncoderParameters.from(JwsHeader.with(MacAlgorithm.HS256).build(), claims))
                .getTokenValue();
    }

    @Test
    void creatingAnOrderReturns201WithLocation() throws Exception {
        Order order = sampleOrder();
        when(placeOrder.place(any())).thenReturn(order);

        mvc.perform(post("/api/orders")
                        .with(jwt().jwt(j -> j.subject("viktor")))
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("""
                                {"lines":[{"sku":"KB-01","quantity":2}]}
                                """))
                .andExpect(status().isCreated())
                .andExpect(header().string("Location", "http://localhost/api/orders/" + order.id()))
                .andExpect(jsonPath("$.status").value("PENDING"))
                .andExpect(jsonPath("$.total").value(99.80));

        // The lines come from the body and the customer from the token, never from the body.
        verify(placeOrder).place(new PlaceOrderCommand("viktor", List.of(new PlaceOrderCommand.Line("KB-01", 2))));
    }

    @Test
    void listsOnePageOfTheCustomersOrders() throws Exception {
        when(getOrders.listByCustomer("viktor", new PageQuery(1, 5)))
                .thenReturn(new PageResult<>(List.of(sampleOrder()), 1, 5, true));

        mvc.perform(get("/api/orders?page=1&size=5").with(jwt().jwt(j -> j.subject("viktor"))))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.content.length()").value(1))
                .andExpect(jsonPath("$.content[0].status").value("PENDING"))
                .andExpect(jsonPath("$.page").value(1))
                .andExpect(jsonPath("$.size").value(5))
                .andExpect(jsonPath("$.hasNext").value(true));
    }

    @Test
    void withoutParametersAsksForTheFirstTenOrders() throws Exception {
        when(getOrders.listByCustomer(any(), any())).thenReturn(emptyPage());

        mvc.perform(get("/api/orders").with(jwt().jwt(j -> j.subject("viktor"))))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.hasNext").value(false));

        verify(getOrders).listByCustomer("viktor", new PageQuery(0, 10));
    }

    @Test
    void aPageSizeAboveTheMaximumReturns400AndNamesTheParameter() throws Exception {
        mvc.perform(get("/api/orders?size=51").with(jwt()))
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.code").value("VALIDATION_FAILED"))
                .andExpect(jsonPath("$.detail", containsString("size")));
    }

    @Test
    void aNegativePageReturns400AndNamesTheParameter() throws Exception {
        mvc.perform(get("/api/orders?page=-1").with(jwt()))
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.code").value("VALIDATION_FAILED"))
                .andExpect(jsonPath("$.detail", containsString("page")));
    }

    @Test
    void validatesTheRequestBodyAndNamesTheField() throws Exception {
        mvc.perform(post("/api/orders")
                        .with(jwt())
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("""
                                {"lines":[{"sku":"KB-01","quantity":101}]}
                                """))
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.code").value("VALIDATION_FAILED"))
                .andExpect(jsonPath("$.detail", containsString("lines[0].quantity")));
    }

    @Test
    void withoutATokenReturnsTheResourceServers401() throws Exception {
        mvc.perform(get("/api/orders"))
                .andExpect(status().isUnauthorized())
                .andExpect(header().string("WWW-Authenticate", startsWith("Bearer")));
    }

    @Test
    void aTokenSignedWithTheServiceKeyIsValid() throws Exception {
        when(getOrders.listByCustomer(any(), any())).thenReturn(emptyPage());
        String valid = token(jwtEncoder, Instant.now().plus(Duration.ofMinutes(5)));

        mvc.perform(get("/api/orders").header("Authorization", "Bearer " + valid))
                .andExpect(status().isOk());
    }

    @Test
    void anExpiredTokenReturns401() throws Exception {
        String expired = token(jwtEncoder, Instant.now().minus(Duration.ofMinutes(10)));

        mvc.perform(get("/api/orders").header("Authorization", "Bearer " + expired))
                .andExpect(status().isUnauthorized());
    }

    @Test
    void aTokenSignedWithAnotherKeyReturns401() throws Exception {
        JwtEncoder attacker = new NimbusJwtEncoder(new ImmutableSecret<>(new SecretKeySpec(
                "another-secret-that-is-not-the-service-one".getBytes(StandardCharsets.UTF_8), "HmacSHA256")));
        String forged = token(attacker, Instant.now().plus(Duration.ofMinutes(5)));

        mvc.perform(get("/api/orders").header("Authorization", "Bearer " + forged))
                .andExpect(status().isUnauthorized());
    }

    @Test
    void anotherCustomersOrderReturns404() throws Exception {
        Order order = sampleOrder();
        when(getOrders.getById(eq(order.id()), eq("viktor"))).thenThrow(new OrderNotFoundException(order.id()));

        mvc.perform(get("/api/orders/{id}", order.id().value()).with(jwt().jwt(j -> j.subject("viktor"))))
                .andExpect(status().isNotFound())
                .andExpect(jsonPath("$.code").value("ORDER_NOT_FOUND"))
                .andExpect(jsonPath("$.params").doesNotExist());
    }

    @Test
    void cancellingANonPendingOrderReturns409() throws Exception {
        OrderId id = OrderId.newId();
        when(cancelOrder.cancel(eq(id), eq("viktor")))
                .thenThrow(new InvalidOrderStateException("no", OrderStatus.CONFIRMED));

        mvc.perform(post("/api/orders/{id}/cancel", id.value()).with(jwt().jwt(j -> j.subject("viktor"))))
                .andExpect(status().isConflict())
                .andExpect(jsonPath("$.code").value("ORDER_NOT_PENDING"))
                .andExpect(jsonPath("$.params.status").value("CONFIRMED"));
    }

    @Test
    void aConcurrencyConflictWhenCancellingReturns409AndNot500() throws Exception {
        OrderId id = OrderId.newId();
        when(cancelOrder.cancel(eq(id), eq("viktor")))
                .thenThrow(new OptimisticLockingFailureException("another transaction won"));

        mvc.perform(post("/api/orders/{id}/cancel", id.value()).with(jwt().jwt(j -> j.subject("viktor"))))
                .andExpect(status().isConflict())
                .andExpect(jsonPath("$.code").value("CONCURRENT_UPDATE"));
    }

    @Test
    void aDomainErrorReturns400WithItsCodeAndItsData() throws Exception {
        when(placeOrder.place(any())).thenThrow(new InvalidOrderException(OrderError.UNKNOWN_PRODUCT,
                "Product XX-99 is not in the catalog", Map.of("sku", "XX-99")));

        mvc.perform(post("/api/orders")
                        .with(jwt().jwt(j -> j.subject("viktor")))
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("""
                                {"lines":[{"sku":"XX-99","quantity":1}]}
                                """))
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.code").value("UNKNOWN_PRODUCT"))
                .andExpect(jsonPath("$.params.sku").value("XX-99"))
                .andExpect(jsonPath("$.detail").value("Product XX-99 is not in the catalog"));
    }

    @Test
    void ifTheCatalogDoesNotRespondReturns503() throws Exception {
        when(placeOrder.place(any())).thenThrow(new CatalogUnavailableException(new RuntimeException("timeout")));

        mvc.perform(post("/api/orders")
                        .with(jwt().jwt(j -> j.subject("viktor")))
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("""
                                {"lines":[{"sku":"KB-01","quantity":1}]}
                                """))
                .andExpect(status().isServiceUnavailable())
                .andExpect(jsonPath("$.code").value("CATALOG_UNAVAILABLE"));
    }
}
